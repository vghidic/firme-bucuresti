"""Export the public PostgreSQL table definitions to a repository file."""

from __future__ import annotations

import argparse
import os
from pathlib import Path

import psycopg


def quote_identifier(value: str) -> str:
    return '"' + value.replace('"', '""') + '"'


def connect() -> psycopg.Connection:
    return psycopg.connect(
        host=os.environ.get("POSTGRES_HOST", "localhost"),
        port=int(os.environ.get("POSTGRES_PORT", "5432")),
        dbname=os.environ.get("POSTGRES_DB", "firme"),
        user=os.environ.get("POSTGRES_USER", "firme"),
        password=os.environ.get("POSTGRES_PASSWORD", "change-me"),
    )


def export_schema(connection: psycopg.Connection, output_path: Path) -> int:
    with connection.cursor() as cursor:
        cursor.execute(
            """
            SELECT
                c.table_name,
                c.column_name,
                c.data_type,
                c.udt_name,
                c.character_maximum_length,
                c.is_nullable,
                c.column_default,
                COALESCE(
                    (
                        SELECT string_agg(kcu.column_name, ', ' ORDER BY kcu.ordinal_position)
                        FROM information_schema.table_constraints tc
                        JOIN information_schema.key_column_usage kcu
                          ON tc.constraint_name = kcu.constraint_name
                         AND tc.table_schema = kcu.table_schema
                         AND tc.table_name = kcu.table_name
                        WHERE tc.constraint_type = 'PRIMARY KEY'
                          AND tc.table_schema = c.table_schema
                          AND tc.table_name = c.table_name
                    ),
                    ''
                ) AS primary_key_columns,
                (
                    SELECT ctu.reltuples::bigint
                    FROM pg_class ctu
                    JOIN pg_namespace nsp
                      ON nsp.oid = ctu.relnamespace
                    WHERE nsp.nspname = c.table_schema
                      AND ctu.relname = c.table_name
                ) AS estimated_row_count
            FROM information_schema.columns c
            WHERE c.table_schema = 'public'
            ORDER BY c.table_name, c.ordinal_position
            """
        )
        rows = cursor.fetchall()

    tables: dict[str, list[tuple]] = {}
    for row in rows:
        tables.setdefault(row[0], []).append(row)

    lines = [
        "-- PostgreSQL public table schema",
        "-- Generated by scripts/export_postgres_schema.py",
        "-- This file contains definitions only; it does not contain table data.",
        "",
    ]
    for table_name, columns in tables.items():
        primary_key = next(
            (column[7] for column in columns if column[7]),
            "",
        )
        estimated_row_count = columns[0][8]
        lines.append(
            f"-- Estimated row count: {estimated_row_count:,}"
        )
        lines.append(f"CREATE TABLE {quote_identifier('public')}.{quote_identifier(table_name)} (")
        definitions = []
        for (
            _,
            column_name,
            data_type,
            udt_name,
            max_length,
            nullable,
            default,
            _,
            _,
        ) in columns:
            if data_type == "USER-DEFINED":
                type_name = quote_identifier(udt_name)
            elif data_type == "character varying" and max_length:
                type_name = f"character varying({max_length})"
            else:
                type_name = data_type
            definition = f"    {quote_identifier(column_name)} {type_name}"
            if nullable == "NO":
                definition += " NOT NULL"
            if default is not None:
                definition += f" DEFAULT {default}"
            definitions.append(definition)
        if primary_key:
            definitions.append(
                f"    PRIMARY KEY ({', '.join(quote_identifier(column.strip()) for column in primary_key.split(','))})"
            )
        lines.append(",\n".join(definitions))
        lines.append(");")
        lines.append("")

    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text("\n".join(lines), encoding="utf-8")
    return len(tables)


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Export public PostgreSQL table schemas without table data."
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=Path("postgres_schema.sql"),
        help="Output schema file (default: postgres_schema.sql).",
    )
    args = parser.parse_args()

    with connect() as connection:
        table_count = export_schema(connection, args.output)
    print(f"Exported {table_count} table schemas to {args.output}")


if __name__ == "__main__":
    main()
